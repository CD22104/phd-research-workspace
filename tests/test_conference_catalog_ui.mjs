// Run against an isolated localhost D1; never writes to the live workspace.
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const origin=process.argv[2]||'http://127.0.0.1:18986';
assert(['localhost','127.0.0.1'].includes(new URL(origin).hostname),'Local database only');
const out=process.env.CONFERENCE_TEST_OUTPUT||'/tmp/honey-conference-catalog';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Los_Angeles'});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.clock.install({time:new Date('2026-10-06T04:00:00Z')});
 const response=await context.request.get(origin+'/api/conferences');assert(response.ok());
 const {conferences}=await response.json();
 assert.equal(conferences.find(c=>c.key==='www-2027').checked_at,'2026-10-06');
 assert.equal(conferences.find(c=>c.key==='cvpr-2027').checked_at,'2026-09-28');
 assert(conferences.every(c=>!c.planned),'New local database has no submission plans');
 await page.goto(origin+'/submissions');
 await page.getByTestId('conference-www-2027').waitFor();
 const filter=page.locator('.submission-toolbar .n-select');
 await filter.click();await page.locator('.n-base-select-option').filter({hasText:/^Web$/}).click();
 assert.equal(await page.locator('.conference-card').count(),1);
 await page.getByRole('button',{name:'展开 WWW 2027',exact:true}).click();
 const www=page.getByTestId('conference-www-2027');
 await www.getByText('2026-10-19 19:59 · 新加坡 ›',{exact:true}).waitFor();
 await www.getByText('2026-10-26 19:59 · 新加坡 ›',{exact:true}).waitFor();
 await page.getByRole('button',{name:'计划投稿 WWW 2027',exact:true}).click();
 await page.getByRole('button',{name:'确认投稿计划',exact:true}).click();
 await page.getByRole('button',{name:'管理投稿计划 WWW 2027',exact:true}).waitFor();
 await page.reload();await page.getByRole('button',{name:'管理投稿计划 WWW 2027',exact:true}).waitFor();
 await page.screenshot({path:out+'/desktop.png'});
 await page.goto(origin+'/?date=2026-10-06');
 await page.getByTestId('countdown-target-www-2027').waitFor();
 assert.equal(await page.getByTestId('countdown-target-ijcai-2027').count(),0);
 await page.goto(origin+'/calendar?date=2026-10-19');
 await page.getByTestId('conference-day-2026-10-19').getByText(/WWW 2027/).first().waitFor();
 await page.goto(origin+'/submissions');
 await filter.click();await page.locator('.n-base-select-option').filter({hasText:/^检索与数据挖掘$/}).click();
 assert.equal(await page.locator('.conference-card').count(),2);
 await page.getByRole('button',{name:'展开 SIGIR 2027',exact:true}).click();
 await page.getByTestId('conference-sigir-2027').getByText(/PROPOSED/).waitFor();
 assert.equal(await page.locator('.milestone-count').count(),0);
 await page.setViewportSize({width:390,height:844});
 await page.goto(origin+'/submissions#www-2027');
 await page.getByTestId('conference-details-www-2027').waitFor();
 await page.waitForFunction(()=>document.documentElement.scrollWidth===390,{},{timeout:5000});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
 await page.screenshot({path:out+'/mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: API metadata, dynamic area filters, WWW plan persists, Today countdown, Singapore calendar date, tentative dates, mobile layout');
}finally{await browser.close();}
